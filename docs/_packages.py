"""Find every package under src/ and work out how the docs reach it.

Used by conf.py (to set up sys.path and write the launch-file page) and by
check_coverage.py (to fail the build if a package is missing from the docs).
"""
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src"
_SKIP = {"test", "tests", "docs"}


def discover():
    """Return ``(importable, file_only)``.

    ``importable`` maps a top-level module name to the directory that has to be
    on ``sys.path`` to import it. The module sits either at ``src/<pkg>/<module>/``
    (ament_python layout) or at ``src/<pkg>/pkg/<module>/`` (plain Python layout).

    ``file_only`` lists the packages under src/ with Python files but no importable
    module (launch files and config scripts).
    """
    importable, file_only = {}, []
    for pkg in sorted(p for p in SRC.iterdir() if p.is_dir() and not p.name.startswith(".")):
        found = False
        for root in (pkg, pkg / "pkg"):
            for init in sorted(root.glob("*/__init__.py")):
                if init.parent.name in _SKIP:
                    continue
                importable[init.parent.name] = root
                found = True
        if not found and any(pkg.rglob("*.py")):
            file_only.append(pkg.name)
    return importable, file_only


def write_file_pages(out_dir, file_only):
    """Write ``launch_files.rst`` listing every Python file of the file-only packages.

    These files are not importable (launch files have dotted names and no
    ``__init__.py``), so autodoc cannot reach them. They are shown as source
    with ``literalinclude`` instead, which needs no imports and so no mocks.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(exist_ok=True)
    docs_dir = out_dir.parent
    lines = [
        "================================",
        "Launch Files and Config Scripts",
        "================================",
        "",
        "Packages under ``src/`` with no importable Python module. Their Python",
        "files are shown as source. This page is generated by ``conf.py``.",
        "",
    ]
    if not file_only:
        lines += ["Every package under ``src/`` has an importable module.", ""]
    for name in file_only:
        lines += [name, "=" * len(name), ""]
        files = sorted(
            f for f in (SRC / name).rglob("*.py")
            if f.name != "setup.py" and not _SKIP & set(f.relative_to(SRC / name).parts)
        )
        for f in files:
            rel = f.relative_to(SRC / name).as_posix()
            # a leading "/" in a literalinclude path is relative to the docs source dir
            target = "/" + Path(*([".."] + list(f.relative_to(docs_dir.parent).parts))).as_posix()
            lines += [
                rel, "-" * len(rel), "",
                f".. literalinclude:: {target}",
                "   :language: python",
                "   :linenos:",
                "",
            ]
    (out_dir / "launch_files.rst").write_text("\n".join(lines), encoding="utf-8")
